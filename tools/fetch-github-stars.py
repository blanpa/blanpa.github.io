#!/usr/bin/env python3
"""Bake who starred and who forked the public repos into data/github_repos.json.

The /status/ page lists the stargazers and forks of every public repository.
The browser could ask GitHub for them, but not for long: without a token the
REST API allows 60 requests an hour per IP, and one page load would spend one
for the repo list, one per repo with a star and one per repo with a fork —
about twenty today. So the deploy workflow asks once a day, with its own
token, and Hugo renders the answer. Each entry keeps its timestamp, which is
what lets the page mark a star as new since the last visit.

A list that cannot be fetched keeps its last known contents, and if GitHub
does not answer at all the committed file stays untouched — a failed request
must never read as everybody having un-starred.

    tools/fetch-github-stars.py                       60 requests/hour
    GITHUB_TOKEN=$(gh auth token) tools/fetch-github-stars.py

Needs nothing but the standard library.
"""

import datetime
import json
import os
import sys
import urllib.request
from pathlib import Path

USER = "blanpa"
API = "https://api.github.com"
OUT = Path(__file__).resolve().parent.parent / "data" / "github_repos.json"
TOKEN = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")


def warn(message):
    print(f"::warning::{message}")


def pages(path, accept="application/vnd.github+json"):
    """Every page of a list endpoint — or None if any request fails, because
    the first half of a list is worse than the list from yesterday."""
    items, page = [], 1
    while True:
        url = f"{API}{path}{'&' if '?' in path else '?'}per_page=100&page={page}"
        request = urllib.request.Request(url, headers={"Accept": accept})
        if TOKEN:
            request.add_header("Authorization", f"Bearer {TOKEN}")
        try:
            with urllib.request.urlopen(request, timeout=20) as response:
                batch = json.load(response)
        except Exception as exc:
            warn(f"{url} failed: {exc}")
            return None
        items += batch
        if len(batch) < 100:
            return items
        page += 1


def main():
    repos = pages(f"/users/{USER}/repos?type=owner")
    if not repos:
        warn("GitHub returned no repositories — keeping the committed file unchanged")
        return 0

    try:
        previous = {r["name"]: r for r in json.loads(OUT.read_text())["repos"]}
    except (OSError, ValueError, KeyError):
        previous = {}

    out, carried = [], 0
    for repo in repos:
        # Forks of other people's projects are not mine to count stars on.
        if repo["fork"] or repo["private"]:
            continue
        name = repo["name"]
        entry = {
            "name": name,
            "stars": repo["stargazers_count"],
            "forks": repo["forks_count"],
            "stargazers": [],
            "forked_by": [],
        }
        if not entry["stars"] and not entry["forks"]:
            continue
        last = previous.get(name, {})

        if entry["stars"]:
            # The star+json media type is what adds starred_at to the answer.
            got = pages(f"/repos/{USER}/{name}/stargazers", "application/vnd.github.star+json")
            if got is None:
                entry["stargazers"] = last.get("stargazers", [])
                carried += 1
            else:
                entry["stargazers"] = sorted(
                    ({"login": s["user"]["login"], "at": s["starred_at"]} for s in got if s.get("user")),
                    key=lambda s: s["at"],
                    reverse=True,
                )

        if entry["forks"]:
            got = pages(f"/repos/{USER}/{name}/forks?sort=newest")
            if got is None:
                entry["forked_by"] = last.get("forked_by", [])
                carried += 1
            else:
                for fork in got:
                    by = {
                        "login": fork["owner"]["login"],
                        "repo": fork["full_name"],
                        "at": fork["created_at"],
                    }
                    # A fresh fork inherits the parent's last push date, so
                    # only a later one says somebody did something with it.
                    if fork.get("pushed_at") and fork["pushed_at"] > fork["created_at"]:
                        by["pushed"] = fork["pushed_at"]
                    entry["forked_by"].append(by)
                entry["forked_by"].sort(key=lambda f: f["at"], reverse=True)

        out.append(entry)

    out.sort(key=lambda r: (-r["stars"], -r["forks"], r["name"].lower()))
    data = {
        "note": "Generated by tools/fetch-github-stars.py in the deploy workflow — do not edit by hand.",
        "updated": datetime.date.today().isoformat(),
        "stars": sum(r["stars"] for r in out),
        "forks": sum(r["forks"] for r in out),
        "repos": out,
    }
    OUT.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    print(f"GitHub: {data['stars']} stars and {data['forks']} forks across {len(out)} repos"
          f" — {carried} list(s) carried over")
    return 0


if __name__ == "__main__":
    sys.exit(main())
